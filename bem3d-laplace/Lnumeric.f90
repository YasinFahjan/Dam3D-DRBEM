! Cross Product of Two vectors
 subroutine cross_product(a,b,c)
 real :: a(3),b(3),c(3)
  c(1)=a(2)*b(3)-a(3)*b(2)
  c(2)=a(3)*b(1)-a(1)*b(3)
  c(3)=a(1)*b(2)-a(2)*b(1)
 end subroutine cross_product
! Angle Among Three Points
 Function angle(a,b,c)
 real :: a(3),b(3),c(3)
  angle=acos(sum((b-a)*(b-c))/(sqrt(sum((b-a)**2))*sqrt(sum((b-c)**2))))
 end function angle

